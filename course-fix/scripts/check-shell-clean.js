#!/usr/bin/env node
/* check-shell-clean.js — в поставляемой оболочке курса не должно остаться
 * ни ссылок на внутренний аудит, ни упоминаний инструментов, которыми курс
 * делался.
 * Использование: node check-shell-clean.js <work-dir>
 *
 * Проверяются только файлы, которые открывает студент:
 *   index.html, assets/*.{js,css}, data/*.json, README.txt
 *
 * Каталоги scripts/ и docs/ не проверяются: это рабочий архив автора,
 * в них названия механизмов упоминаются по делу. Разделение проведено
 * явно, потому что прогон по всему дереву даёт ложные срабатывания на
 * самих исправителях.
 *
 * Выход 0 — чисто, 1 — есть находки.
 */
'use strict';

var fs = require('fs');
var path = require('path');

var work = process.argv[2];
if (!work) { console.error('usage: node check-shell-clean.js <work-dir>'); process.exit(2); }

/* Слова и их смысл. Каждое сюда попало потому, что хоть раз всплыло
 * в поставляемом курсе или могло бы всплыть. */
var FORBIDDEN = [
  ['REVIEW_CHECKLIST', 'ссылка на внутренний аудит'],
  ['TBD-REVIEW', 'черновой маркер'],
  ['unreviewed LLM draft', 'упоминание инструмента'],
  ['LLM draft', 'упоминание инструмента'],
  ['Claude', 'название модели'],
  ['ChatGPT', 'название модели'],
  ['GPT-', 'название модели'],
  ['OpenAI', 'название вендора'],
  ['Anthropic', 'название вендора'],
  ['Gemini', 'название модели'],
  ['Qwen', 'название модели'],
  ['language model', 'упоминание инструмента'],
  ['искусственн', 'упоминание инструмента'],
  ['с помощью ЛЛМ', 'упоминание инструмента'],
  ['с помощью LLM', 'упоминание инструмента'],
  ['сгенерирован', 'упоминание инструмента'],
  ['AI-generated', 'упоминание инструмента'],
  ['generated by', 'упоминание инструмента']
];

/* Что именно считать оболочкой курса. */
function shellFiles(dir) {
  var out = [];
  var top = ['index.html', 'README.txt'];
  top.forEach(function (f) {
    var p = path.join(dir, f);
    if (fs.existsSync(p)) out.push(p);
  });
  ['assets', 'data'].forEach(function (sub) {
    var d = path.join(dir, sub);
    if (!fs.existsSync(d)) return;
    fs.readdirSync(d).forEach(function (f) {
      if (/\.(js|css|json|html|txt)$/.test(f)) out.push(path.join(d, f));
    });
  });
  return out;
}

var files = shellFiles(work);
if (!files.length) {
  console.error('check-shell-clean: в ' + work + ' не найдено файлов оболочки');
  process.exit(2);
}

var hits = [];
var bytes = 0;

files.forEach(function (p) {
  var raw;
  try { raw = fs.readFileSync(p, 'utf8'); } catch (e) { return; }
  bytes += Buffer.byteLength(raw);
  var lower = raw.toLowerCase();
  FORBIDDEN.forEach(function (rule) {
    var needle = rule[0];
    var n = lower.split(needle.toLowerCase()).length - 1;
    if (n > 0) {
      // Контекст первого вхождения — чтобы отличить настоящее упоминание
      // от совпадения внутри слова.
      var at = lower.indexOf(needle.toLowerCase());
      var ctx = raw.slice(Math.max(0, at - 70), at + needle.length + 70)
        .replace(/\s+/g, ' ');
      hits.push({ file: path.relative(work, p), what: rule[0], why: rule[1],
        n: n, ctx: ctx });
    }
  });
});

console.log('check-shell-clean: ' + files.length + ' файлов оболочки, ' +
  Math.round(bytes / 1024) + ' КБ');

if (hits.length) {
  console.log('  НАХОДКИ (' + hits.length + '):');
  hits.forEach(function (h) {
    console.log('    x ' + h.file + ' — ' + h.what + ' (' + h.why + ') ×' + h.n);
    console.log('        …' + h.ctx + '…');
  });
  process.exit(1);
}
console.log('  ни ссылок на аудит, ни упоминаний инструментов');
console.log('check-shell-clean: OK');
