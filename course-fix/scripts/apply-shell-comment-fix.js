#!/usr/bin/env node
/* apply-shell-comment-fix.js — убрать из оболочки названия сборки.
 * Использование: node apply-shell-comment-fix.js <work-dir>
 *
 * Round 24 (D20). Шапка app.js объясняла, откуда берётся встроенный снимок
 * данных, и называла при этом скрипт, который его делает. Комментарий читает
 * только тот, кто правит курс, — но строка в поставляемом курсе не должна
 * называть инструменты, которыми курс делался. Смысл сохраняем, название
 * убираем: читателю важно, что снимок встроен и курс работает с file://.
 *
 * Идемпотентно: совпадение по точному тексту, при отсутствии — «уже применено».
 */
'use strict';
var fs = require('fs');
var path = require('path');

var work = process.argv[2];
if (!work) { console.error('usage: node apply-shell-comment-fix.js <work-dir>'); process.exit(2); }
var f = path.join(work, 'assets', 'app.js');
var raw = fs.readFileSync(f, 'utf8');

var from = [
  ' * Data: app.js tries fetch(\'data/*.json\') first (works over http) and falls',
  ' * back to the global COURSE_DATA from assets/data-embed.js (generated by',
  ' * scripts/embed.js) so the course also works from file://.'
].join('\n');

var to = [
  ' * Data: app.js tries fetch(\'data/*.json\') first (works over http) and falls',
  ' * back to the global COURSE_DATA from assets/data-embed.js, so the course',
  ' * also works when opened straight from the filesystem.'
].join('\n');

if (raw.indexOf(from) >= 0) {
  fs.writeFileSync(f, raw.replace(from, to));
  console.log('apply-shell-comment-fix: название сборки убрано из шапки app.js');
} else if (raw.indexOf(to) >= 0) {
  console.log('apply-shell-comment-fix: already applied');
} else {
  console.error('apply-shell-comment-fix: ожидаемый текст не найден');
  process.exit(1);
}
