#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_pilot_sheet.py — the observer sheet for a pilot run.

WHY THIS IS GENERATED
  A pilot sheet lists, per step, what the right answer is and what to watch for.
  Typed by hand it becomes a second, unaudited copy of the answer key — exactly
  the failure the case generator exists to prevent. So the sheet is built from
  data/cases.json, and this script refuses to write if a case has no key for a
  step.

USAGE
  python3 scripts/gen_pilot_sheet.py            # write docs/pilot-sheet.md
  python3 scripts/gen_pilot_sheet.py --check    # fail if the file is stale
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CASES = os.path.join(ROOT, "data", "cases.json")
OUT = os.path.join(ROOT, "docs", "pilot-sheet.md")

HEADER = """# Pilot sheet — observer copy

Generated by `scripts/gen_pilot_sheet.py` from `data/cases.json`. Do not edit by
hand: every key below comes from the same generator that grades the case, so if a
key changes here it changed in the course too.

One row per step. "Expected" is the key; "watch for" is the wrong answer that
looks plausible — the thing a participant is most likely to write.

Protocol: `docs/pilot-protocol.md`.
"""


def plain(step):
    """The answer as a person writes it."""
    if step["type"] == "numeric":
        v = step["answer"]["value"]
        if isinstance(v, float) and v == int(v):
            v = int(v)
        unit = step["answer"].get("unit", "")
        return str(v) + ("" if unit in ("", "dimensionless") else " " + unit)
    for o in step.get("options", []):
        if o["id"] == step["answer"]["value"]:
            return "option %s — “%s”" % (o["id"], o["text"])
    return "option " + str(step["answer"]["value"])


def tolerance(step):
    if step["type"] != "numeric":
        return "—"
    t = step["answer"].get("tolerance")
    return ("±" + str(t)) if t is not None else "—"


def trap(step):
    """The most plausible wrong answer, taken from the step's own feedback."""
    bad = (step.get("feedbackWrong") or "").strip()
    return bad if bad else "—"


def main(argv=None):
    check = "--check" in sys.argv
    with open(CASES, encoding="utf-8-sig") as fh:
        doc = json.load(fh)

    lines = [HEADER]
    missing = []
    for c in doc["cases"]:
        pts = sum(r["points"] for r in c["rubric"])
        lines.append("""
---

## %s — %s

`#/c/%s` · module %s · %d steps · %d rubric points · about %d min

| # | Step | Type | Expected | Tolerance | Watch for |
|---|---|---|---|---|---|""" % (
            c["caseId"], c["title"], c["caseId"], c["moduleId"],
            len(c["steps"]), pts, c["estMinutes"]))
        for i, st in enumerate(c["steps"], 1):
            if "answer" not in st or st["answer"].get("value") is None:
                missing.append("%s/%s" % (c["caseId"], st["id"]))
                continue
            lines.append("| %d | %s | %s | %s | %s | %s |" % (
                i,
                st["prompt"].replace("|", "\\|"),
                st["type"],
                plain(st).replace("|", "\\|"),
                tolerance(st),
                trap(st).replace("|", "\\|"),
            ))
        lines.append("""
**Rubric** (pass mark %d %%):""" % 80)
        for r in c["rubric"]:
            lines.append("- %s — %d pts (%s)" % (r["criterion"], r["points"],
                                                 ", ".join(r.get("steps", []))))

    if missing:
        print("pilot sheet: %d step(s) have no key: %s" % (len(missing), ", ".join(missing)),
              file=sys.stderr)
        return 1

    text = "\n".join(lines) + "\n"
    if check:
        if not os.path.exists(OUT):
            print("pilot sheet --check: MISSING", file=sys.stderr)
            return 1
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                print("pilot sheet --check: STALE (re-run without --check)", file=sys.stderr)
                return 1
        print("pilot sheet --check: OK (%d cases)" % len(doc["cases"]))
        return 0

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    steps = sum(len(c["steps"]) for c in doc["cases"])
    print("wrote docs/pilot-sheet.md — %d cases, %d steps" % (len(doc["cases"]), steps))
    return 0


if __name__ == "__main__":
    sys.exit(main())
