#!/usr/bin/env node
/* =========================================================================
 * edit-tool.js — the authoring surface for a lesson
 *
 *   node src/phase5/edit-tool.js m01l02 --brief      # what I read before editing
 *   node src/phase5/edit-tool.js m01l02 --export     # <id>.book.json to fill in
 *   node src/phase5/edit-tool.js m01l02 --apply      # book.json -> edit/<id>.js
 *   node src/phase5/edit-tool.js m01l02 --check-raw  # does .raw differ from JSON?
 *
 * The book is JSON because it is edited by a tool, but the .raw field is plain
 * text on purpose: a JSON string literal would force every quote in the lesson
 * to be escaped, and an escaped lesson is unreadable at the moment it is being
 * rewritten. The .raw is split into paragraphs on blank lines; each paragraph
 * becomes one <p>. Only the first line of each entry is prefixed with the
 * target marker:
 *
 *     [0] PARAGRAPH BODY
 *     [3] PARAGRAPH BODY
 *
 * and a number in brackets means "this text replaces the paragraphs merged from
 * original entries 1..3", which is what you use when three long paragraphs
 * should become two better ones.
 * ========================================================================= */
'use strict';
const fs = require('fs');
const path = require('path');
const { BASELINE_PATH, readJson, words, bodies } = require('./lib');

const EDIT = path.join(__dirname, 'edit');
const id = process.argv[2];
if (!id) { console.log('usage: node src/phase5/edit-tool.js <lessonId> [--brief|--export|--apply|--check-raw]'); process.exit(2); }
const lessons = readJson(BASELINE_PATH);
const l = lessons.filter(function (x) { return x.lessonId === id; })[0];
if (!l) { console.log('!! no lesson ' + id); process.exit(2); }
const bookPath = path.join(EDIT, id + '.book.json');
const jsPath = path.join(EDIT, id + '.js');

function brief() {
  console.log('\n===== ' + l.lessonId + ' | ' + l.title);
  console.log('module ' + l.moduleId + ', stage ' + l.stageId + ', sources ' + (l.sources || []).join(' '));
  l.goals.forEach(function (g) { console.log('goal: ' + g.text); });
  l.content.theory.forEach(function (t, i) {
    if (!t) return;
    const list = bodies(t);
    if (!list.length) return;
    console.log('\n[' + i + '] (' + list.map(function (p) { return words(p).length; }).join('+') + 'w) ' + (t.h || ''));
    list.forEach(function (p) { console.log('   ' + String(p).trim()); });
  });
  console.log('\nCALC TASK :: ' + l.content.calc.task);
  console.log('CALC SOLUTION :: ' + l.content.calc.solution);
  console.log('DEFECT symptom :: ' + l.content.defect.symptom);
  console.log('DEFECT cause   :: ' + l.content.defect.cause);
  console.log('DEFECT action  :: ' + l.content.defect.action);
}

/* The .raw is built from the baseline: every paragraph exactly as it stands, so
 * the editor starts from the real text rather than from a memory of it. */
function exportBook() {
  const existing = fs.existsSync(bookPath) ? readJson(bookPath) : null;
  const entries = [];
  l.content.theory.forEach(function (t, i) {
    const list = bodies(t);
    if (!list.length) return;
    entries.push({ index: i, heading: t.h || '', raw: list.join('\n\n') });
  });
  const book = existing || {
    lessonId: id,
    title: l.title,
    takeaways: [],
    mistakes: [{ mistake: '', instead: '' }, { mistake: '', instead: '' }, { mistake: '', instead: '' }],
    terms: [{ term: '', def: '' }, { term: '', def: '' }]
  };
  book.entries = entries;
  if (!existing) fs.writeFileSync(bookPath, JSON.stringify(book, null, 2) + '\n');
  console.log((existing ? 'refreshed entries in ' : 'wrote ') + path.relative(process.cwd(), bookPath));
  console.log(entries.length + ' entries, ' + entries.reduce(function (a, e) { return a + words(e.raw).length; }, 0) + ' words');
}

/* Parse the .raw of one entry into the replacement list for apply.js. */
function parseRaw(raw) {
  return String(raw).split(/\n\s*\n/).map(function (p) {
    return p.replace(/\s+/g, ' ').trim();
  }).filter(Boolean);
}

function applyBook() {
  if (!fs.existsSync(bookPath)) { console.log('!! no book at ' + bookPath); process.exit(2); }
  const book = readJson(bookPath);
  /* A merged entry has its raw written under the FIRST index of the range and
   * an `merge` field naming the rest, so nothing has to be guessed. */
  const lines = [];
  lines.push('/* ' + id + ' — ' + l.title);
  lines.push(' *');
  lines.push(' * Generated by src/phase5/edit-tool.js from ' + path.basename(bookPath) + '.');
  lines.push(' * Edit the book, not this file: the book keeps the original text next to');
  lines.push(' * the rewrite so the diff in docs/phase5-diff can be regenerated.');
  lines.push(' */');
  lines.push('module.exports = {');
  const paras = [];
  book.entries.forEach(function (e) {
    const out = parseRaw(e.raw);
    if (!out.length) return;
    const idents = Array.isArray(e.merge) && e.merge.length ? [e.index].concat(e.merge) : [e.index];
    idents.forEach(function (k) {
      paras.push('    ' + k + ': { p: [' + out.map(function (p) {
        return '\n      ' + JSON.stringify(p);
      }).join(',') + '\n    ] }');
    });
  });
  lines.push('  paragraphs: {');
  lines.push(paras.join(',\n'));
  lines.push('  },');
  lines.push('  takeaways: [');
  lines.push(book.takeaways.map(function (t) { return '    ' + JSON.stringify(t); }).join(',\n'));
  lines.push('  ],');
  lines.push('  mistakes: [');
  lines.push(book.mistakes.map(function (m) {
    return '    { mistake: ' + JSON.stringify(m.mistake) + ', instead: ' + JSON.stringify(m.instead) + ' }';
  }).join(',\n'));
  lines.push('  ],');
  lines.push('  terms: [');
  lines.push(book.terms.map(function (t) {
    return '    { term: ' + JSON.stringify(t.term) + ', def: ' + JSON.stringify(t.def) + ' }';
  }).join(',\n'));
  lines.push('  ]');
  lines.push('};');
  fs.writeFileSync(jsPath, lines.join('\n') + '\n');
  console.log('wrote ' + path.relative(process.cwd(), jsPath) + ' (' + paras.length + ' paragraph slots)');
}

const flag = process.argv[3] || '--brief';
if (flag === '--brief') brief();
else if (flag === '--export') exportBook();
else if (flag === '--apply') applyBook();
else console.log('unknown flag ' + flag);
